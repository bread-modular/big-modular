#!/usr/bin/env python3
"""The demo loop through the master chain on the emulated ESP32-S3 (see audio.sh).

  audio.py prepare --out DIR --header main/audio_in.h
      writes kick.wav / mix.wav (two bars of ../demo.py's loop, 16 bit) and the
      settings files to DIR, and the same samples and settings as a C header
  audio.py compare --out DIR --log build-audio/qemu.log --render ../ms_render
      turns the samples QEMU printed into DIR/qemu-<set>.wav, renders the same
      inputs on this computer (DIR/host-<set>.wav) and compares the two
"""
import argparse
import os
import subprocess
import sys
import wave

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from demo import FS, make_loop, read_wav, write_wav  # noqa: E402

OFF = ["k_hp_on", "k_lim_on", "m_hp_on", "mb_on", "par_on", "eq_lo_on", "eq_hi_on", "lim_on"]
GLUE_ONLY = {k: 0 for k in OFF}
# Name -> settings on top of the factory ones.
SETS = {
    "factory": {},
    # The glue alone, working hard, with its sidechain filter and soft clip.
    "glue": dict(GLUE_ONLY, glue_thr=-20, glue_ratio=1, glue_att=4, glue_sc_hp=100, glue_clip=1),
    # The stiffest loop: 10:1 at the fastest attack and release.
    "glue-fast": dict(GLUE_ONLY, glue_thr=-24, glue_ratio=2, glue_att=0, glue_rel=0),
}


def settings_text(name):
    return "".join("set %s %s\n" % kv for kv in SETS[name].items())


def prepare(args):
    os.makedirs(args.out, exist_ok=True)
    kick, mix, beat = make_loop(bars=2)
    n = len(kick) // 16 * 16
    q = {}
    for name, x in (("kick", kick), ("mix", mix)):
        path = os.path.join(args.out, name + ".wav")
        write_wav(path, x[:n])
        with wave.open(path, "rb") as w:
            q[name] = np.frombuffer(w.readframes(n), dtype="<i2")
    for name in SETS:
        with open(os.path.join(args.out, name + ".txt"), "w") as f:
            f.write(settings_text(name))
    with open(args.header, "w") as f:
        f.write("// Generated by audio.py: do not edit.\n#include <stdint.h>\n\n#define AUDIO_N %d\n" % n)
        for name in ("kick", "mix"):
            f.write("static const int16_t audio_%s[AUDIO_N] = {\n" % name)
            for i in range(0, n, 16):
                f.write(",".join(str(v) for v in q[name][i : i + 16]) + ",\n")
            f.write("};\n")
        f.write("#define AUDIO_SETS %d\nstatic const char *const audio_sets[AUDIO_SETS][2] = {\n" % len(SETS))
        for name in SETS:
            f.write('    {"%s", "%s"},\n' % (name, settings_text(name).replace("\n", "\\n")))
        f.write("};\n")
    print("%d frames (%.2f s) -> %s" % (n, n / FS, args.header))


def write_wav24(path, v):
    b = np.frombuffer((v.astype("<i4")).tobytes(), dtype=np.uint8).reshape(-1, 4)[:, :3]
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(3)
        w.setframerate(FS)
        w.writeframes(b.tobytes())


def compare(args):
    got = {name: [] for name in SETS}
    with open(args.log, "r", errors="replace") as f:
        for line in f:
            p = line.split()
            if len(p) == 3 and p[0] == "AUD" and p[1] in got:
                got[p[1]].append(p[2])
            elif line.startswith("BENCH"):
                print(line.rstrip())
    kp, mp = os.path.join(args.out, "kick.wav"), os.path.join(args.out, "mix.wav")
    ok = True
    for name in SETS:
        text = "".join(got[name])
        v = np.array([int(text[i : i + 6], 16) for i in range(0, len(text), 6)], dtype=np.int64)
        v = np.where(v >= 1 << 23, v - (1 << 24), v)
        write_wav24(os.path.join(args.out, "qemu-%s.wav" % name), v)
        hp = os.path.join(args.out, "host-%s.wav" % name)
        subprocess.run([args.render, "-s", os.path.join(args.out, name + ".txt"), kp, mp, hp], check=True,
                       capture_output=True)
        host = np.round(read_wav(hp) * 8388608.0).astype(np.int64)
        if len(v) != len(host) or len(v) == 0:
            print("%s: %d samples from QEMU, %d from the host" % (name, len(v), len(host)))
            ok = False
            continue
        diff = np.abs(v - host)
        worst = int(diff.max())
        rms = float(np.sqrt(np.mean(diff.astype(float) ** 2)))
        print("%-10s %d samples, peak %.2f dB: %d differ from the host render, worst by %d of 2^23 (%.0f dB), rms %.2f"
              % (name, len(v), 20 * np.log10(np.abs(v).max() / 8388608.0), int(np.count_nonzero(diff)), worst,
                 20 * np.log10(max(worst, 0.5) / 8388608.0), rms))
        ok = ok and worst <= args.tolerance
    if not ok:
        sys.exit("QEMU and host renders differ by more than %d of 2^23" % args.tolerance)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--out", required=True)
    p.add_argument("--header", required=True)
    p = sub.add_parser("compare")
    p.add_argument("--out", required=True)
    p.add_argument("--log", required=True)
    p.add_argument("--render", required=True)
    p.add_argument("--tolerance", type=int, default=64, help="largest difference allowed, in 24-bit steps")
    args = ap.parse_args()
    (prepare if args.cmd == "prepare" else compare)(args)


if __name__ == "__main__":
    main()
