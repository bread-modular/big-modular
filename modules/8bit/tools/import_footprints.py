"""Import the pinned 8bit footprints into hardware/8BIT.pretty (one-time, reviewable).

The library is rebuilt from scratch: footprints no longer listed are removed.

Run from modules/8bit with KiCad's Python (pcbnew 10):
  python3 -B tools/import_footprints.py [--bread-modular ~/data/projects/bread-modular]

Sources are read-only:
- the Bread Modular AudioJacks library (MIT, Barwise) for the PJ301M-12 jack, with the
  same two edits as modules/midi (decorative F.SilkS arcs removed, F.CrtYd = model
  envelope + 0.25 mm, 3D model -> ${KIPRJMOD}/8BIT.3dshapes/PJ301M-12.step);
- the Bread Modular 8bit `BreadModular_Pots:Potentiometer_RV09` pot footprint, unedited
  (Bread Modular footprints are preferred: the user's builds prove them). Upstream has no 3D
  model; it gets the user-sample RV09 proxy of modules/audio-out (same footprint frame:
  no bushing, 16 mm shaft), copied into 8BIT.3dshapes/RV09_proxy.step;
- the installed KiCad stock library for everything else (including the SW1 6x6 mm THT
  tact switch, `SW_PUSH_6mm_H7.3mm`), unedited except for the recorded VQFN-20 3D-model
  proxy (as modules/midi).

hardware/8BIT.pretty/PROVENANCE.json records source paths and SHA-256 of every input
and output.
"""
import argparse
import hashlib
import json
import shutil
from pathlib import Path

import pcbnew

MODULE = Path(__file__).resolve().parents[1]
STOCK = Path('/usr/share/kicad/footprints')
LIBNAME = '8BIT'

STOCK_FOOTPRINTS = [
    ('LED_THT', 'LED_D3.0mm'),
    ('Package_DFN_QFN', 'VQFN-20-1EP_3x3mm_P0.4mm_EP1.7x1.7mm'),
    ('Package_SO', 'SOIC-8_3.9x4.9mm_P1.27mm'),
    ('Package_TO_SOT_SMD', 'SOT-89-3'),
    ('Package_TO_SOT_SMD', 'SOT-23'),
    ('Package_TO_SOT_SMD', 'SOT-23-5'),
    ('Package_TO_SOT_SMD', 'SOT-323_SC-70'),
    ('Diode_SMD', 'D_SOD-123'),
    ('Resistor_SMD', 'R_0603_1608Metric'),
    ('Resistor_SMD', 'R_1206_3216Metric'),
    ('Capacitor_SMD', 'C_0603_1608Metric'),
    ('Capacitor_SMD', 'C_0805_2012Metric'),
    ('Button_Switch_THT', 'SW_PUSH_6mm_H7.3mm'),
    ('Connector_PinHeader_2.54mm', 'PinHeader_2x05_P2.54mm_Vertical'),
    ('Connector_PinHeader_2.54mm', 'PinHeader_1x02_P2.54mm_Vertical'),
    ('Jumper', 'SolderJumper-2_P1.3mm_Open_RoundedPad1.0x1.5mm'),
    ('Jumper', 'SolderJumper-3_P1.3mm_Open_RoundedPad1.0x1.5mm'),
]

# Bread Modular footprints copied unedited: (library dir relative to the BM repo, name)
BM_FOOTPRINTS = [
    ('modules/8bit/footprints/BreadModular_Pots.pretty', 'Potentiometer_RV09'),
]

# BM footprints without a courtyard: name -> (half-width X, half-height Y) of the added F.CrtYd.
BM_COURTYARD = {}

# BM footprint -> 3D model (in 8BIT.3dshapes) and its recorded source.
BM_MODEL = {'Potentiometer_RV09': ('RV09_proxy.step',
                                   'main:modules/audio-out/hardware/AudioOut.3dshapes/RV09_proxy.step '
                                   '(generated by modules/audio-out/tools/make_pot_model.py; user pot sample)')}

# name -> (step file, courtyard half-width X, courtyard Y top, courtyard Y bottom)
JACKS = {
    'Jack_3.5mm_QingPu_WQP-PJ301M-12_Vertical': ('PJ301M-12.step', 4.75, -6.25, 7.80),
}

# The stock footprint references a model KiCad does not ship; use the only shipped
# 3x3 mm 20-pin P0.4 body (UQFN, thinner than VQFN) as an explicitly recorded visual
# proxy. The <0.4 mm height difference is irrelevant to the panel fit.
MODEL_PROXY = {
    'VQFN-20-1EP_3x3mm_P0.4mm_EP1.7x1.7mm':
        '${KICAD10_3DMODEL_DIR}/Package_DFN_QFN.3dshapes/UQFN-20-1EP_3x3mm_P0.4mm_EP1.85x1.85mm.step',
}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rel(path):
    """Host-neutral provenance path (~ for the home directory)."""
    return str(path).replace(str(Path.home()), '~', 1)


def mm(v):
    return pcbnew.FromMM(v)


def fix_jack(fp, step, hx, ytop, ybot):
    for item in list(fp.GraphicalItems()):
        is_ring = (item.GetLayer() == pcbnew.F_SilkS and item.GetClass() == 'PCB_SHAPE'
                   and item.GetShape() == pcbnew.SHAPE_T_ARC)
        if item.GetLayer() == pcbnew.F_CrtYd or is_ring:
            fp.Delete(item)
    rect = pcbnew.PCB_SHAPE(fp, pcbnew.SHAPE_T_RECT)
    rect.SetLayer(pcbnew.F_CrtYd)
    rect.SetWidth(mm(0.05))
    rect.SetStart(pcbnew.VECTOR2I(mm(-hx), mm(ytop)))
    rect.SetEnd(pcbnew.VECTOR2I(mm(hx), mm(ybot)))
    fp.Add(rect)
    rect.thisown = 0  # the footprint owns it now
    models = fp.Models()
    keep = pcbnew.FP_3DMODEL()
    keep.m_Filename = f'${{KIPRJMOD}}/{LIBNAME}.3dshapes/' + step
    models.clear()
    models.push_back(keep)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bread-modular', default=str(Path.home() / 'data/projects/bread-modular'))
    args = ap.parse_args()
    bm = Path(args.bread_modular)
    hw = MODULE / 'hardware'
    LIB, MODELS = hw / f'{LIBNAME}.pretty', hw / f'{LIBNAME}.3dshapes'
    jacks = bm / 'opt/AudioJacks'
    LIB.mkdir(exist_ok=True)
    for old in LIB.glob('*.kicad_mod'):
        old.unlink()
    MODELS.mkdir(exist_ok=True)
    record = {'footprints': {}, 'models': {}}
    io = pcbnew.PCB_IO_MGR.FindPlugin(pcbnew.PCB_IO_MGR.KICAD_SEXP)
    for lib, name in STOCK_FOOTPRINTS:
        src = STOCK / f'{lib}.pretty' / f'{name}.kicad_mod'
        fp = io.FootprintLoad(str(src.parent), name)
        fp.SetFPID(pcbnew.LIB_ID(LIBNAME, name))
        edits = 'none (native load/save only)'
        if name in MODEL_PROXY:
            models = fp.Models()
            model = models[0]
            missing = model.m_Filename
            model.m_Filename = MODEL_PROXY[name]
            models[0] = model
            edits = f'3D model {missing} is not shipped by KiCad; visual proxy {MODEL_PROXY[name]}'
        io.FootprintSave(str(LIB), fp)
        record['footprints'][name] = {'source': rel(src), 'source_sha256': sha(src),
                                      'license': 'KiCad library CC-BY-SA-4.0-with-exception',
                                      'edits': edits}
    for libdir, name in BM_FOOTPRINTS:
        src = bm / libdir / f'{name}.kicad_mod'
        fp = io.FootprintLoad(str(src.parent), name)
        fp.SetFPID(pcbnew.LIB_ID(LIBNAME, name))
        edits = 'none (native load/save only); no 3D model upstream'
        if name in BM_COURTYARD:
            hx, hy = BM_COURTYARD[name]
            assert not any(i.GetLayer() == pcbnew.F_CrtYd for i in fp.GraphicalItems())
            silk = [i for i in fp.GraphicalItems() if i.GetLayer() == pcbnew.F_SilkS]
            assert len(silk) == 4, len(silk)
            for item in silk:
                fp.Delete(item)
            rect = pcbnew.PCB_SHAPE(fp, pcbnew.SHAPE_T_RECT)
            rect.SetLayer(pcbnew.F_CrtYd)
            rect.SetWidth(mm(0.05))
            rect.SetStart(pcbnew.VECTOR2I(mm(-hx), mm(-hy)))
            rect.SetEnd(pcbnew.VECTOR2I(mm(hx), mm(hy)))
            fp.Add(rect)
            rect.thisown = 0
            edits = (f'copper unedited; added F.CrtYd X +/-{hx}, Y +/-{hy} (upstream has none); removed the 4 '
                     'F.SilkS body lines that overlap its pads (hidden under the panel); no 3D model upstream')
        if name in BM_MODEL:
            step, origin = BM_MODEL[name]
            model = pcbnew.FP_3DMODEL()
            model.m_Filename = f'${{KIPRJMOD}}/{LIBNAME}.3dshapes/' + step
            fp.Models().clear()
            fp.Models().push_back(model)
            edits = f'copper unedited; 3D model -> ${{KIPRJMOD}}/{LIBNAME}.3dshapes/{step} (upstream has none)'
            record['models'][step] = {'source': origin, 'sha256': sha(MODELS / step),
                                      'license': 'Big Modular (this repository)'}
        io.FootprintSave(str(LIB), fp)
        record['footprints'][name] = {'source': rel(src), 'source_sha256': sha(src),
                                      'license': 'MIT (c) 2024 Arunoda Susiripala (Bread Modular LICENSE)',
                                      'edits': edits}
    for name, (step, hx, ytop, ybot) in JACKS.items():
        src = jacks / 'AudioJacks.pretty' / f'{name}.kicad_mod'
        fp = io.FootprintLoad(str(src.parent), name)
        fp.SetFPID(pcbnew.LIB_ID(LIBNAME, name))
        fix_jack(fp, step, hx, ytop, ybot)
        io.FootprintSave(str(LIB), fp)
        record['footprints'][name] = {
            'source': rel(src), 'source_sha256': sha(src), 'license': 'MIT (c) 2021 Barwise',
            'edits': 'removed two decorative F.SilkS arcs crossing the TN/R pad; '
                     f'F.CrtYd -> X +/-{hx}, Y {ytop}..{ybot} (model envelope +0.25); '
                     f'3D model -> ${{KIPRJMOD}}/{LIBNAME}.3dshapes/{step}'}
        model_src = jacks / 'AudioJacks.3dshapes' / step
        shutil.copyfile(model_src, MODELS / step)
        record['models'][step] = {'source': rel(model_src), 'sha256': sha(model_src),
                                  'license': 'MIT (c) 2021 Barwise'}
    shutil.copyfile(jacks / 'LICENSE', MODELS / 'LICENSE-AudioJacks-MIT.txt')
    for name in record['footprints']:
        record['footprints'][name]['output_sha256'] = sha(LIB / f'{name}.kicad_mod')
    (LIB / 'PROVENANCE.json').write_text(json.dumps(record, indent=2) + '\n')
    (hw / 'fp-lib-table').write_text(
        f'(fp_lib_table (version 7) (lib (name "{LIBNAME}") (type "KiCad") (uri "${{KIPRJMOD}}/{LIBNAME}.pretty") '
        f'(options "") (descr "8bit module pinned footprints; see {LIBNAME}.pretty/PROVENANCE.json")))\n')
    print(json.dumps({k: sorted(v) for k, v in record.items()}, indent=2))


if __name__ == '__main__':
    main()
